-- Ejecutar solo si se administra el esquema manualmente desde SQL Editor.
-- Con spring.jpa.hibernate.ddl-auto=update, Spring Boot crea esta tabla al iniciar.
-- No incluye datos de tarjetas ni credenciales de Yape: el pago es simulado.

CREATE TABLE IF NOT EXISTS public.carrito_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES public.usuarios(id),
    producto_id BIGINT NOT NULL REFERENCES public.productos(id),
    cantidad INTEGER NOT NULL CHECK (cantidad BETWEEN 1 AND 100),
    fecha_agregado TIMESTAMP NOT NULL,
    CONSTRAINT uq_carrito_usuario_producto UNIQUE (usuario_id, producto_id)
);

CREATE INDEX IF NOT EXISTS idx_carrito_items_usuario
    ON public.carrito_items(usuario_id);

-- Solo el backend mediante JDBC debe consultar el carrito.
ALTER TABLE public.carrito_items ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON public.carrito_items FROM anon, authenticated;
REVOKE ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;
